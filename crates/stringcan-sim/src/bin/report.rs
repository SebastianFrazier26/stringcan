//! Renders the demo report: `cargo run -p stringcan-sim --bin report > docs/demo/REPORT.md`

use std::fmt::Write;

use stringcan_core::{Config, FeeModel};
use stringcan_sim::{joiner_walkthrough, money, run, zero_fee, Row, Step};

fn table(rows: &[Row]) -> String {
    let mut s = String::from(
        "| period | participants | each pays (min-max) | paid to owner | credits returned | reserve after | deficit carried |\n|---:|---:|---:|---:|---:|---:|---:|\n",
    );
    for r in rows {
        let each = if r.min_share == r.max_share {
            money(r.min_share)
        } else {
            format!("{} - {}", money(r.min_share), money(r.max_share))
        };
        let _ = writeln!(
            s,
            "| {} | {} | {} | {} | {} | {} | {} |",
            r.period,
            r.participants,
            each,
            money(r.payout),
            money(r.credits_issued),
            money(r.reserve),
            money(r.deficit_out)
        );
    }
    s
}

fn main() {
    let mut out = String::new();
    out.push_str("# stringcan demo report\n\nGenerated by `cargo run -p stringcan-sim --bin report`. Every number below comes from the real engine (not a mock), audited for money conservation after each settlement. Processor fees are set to zero here so the arithmetic is easy to follow; the fee section at the end shows the gross-up.\n\nPeriod 1 is always a bootstrap: whoever subscribes first is the only committed person and funds it alone (design doc, section 5). The interesting rows start at period 2, and the large credit in period 2 is the bootstrap prepayers getting back what they paid before the crowd had arrived.\n\n");

    // 1. Steady
    let steady = run(zero_fee(), 20_000, 20, &vec![Step::default(); 5]);
    out.push_str("## 1. Steady state\n\n20 subscribers, 200.00 upkeep. Everyone pays exactly 10.00 every period; nothing is left over.\n\n");
    out.push_str(&table(&steady.rows));

    // 2. Growth burst
    let mut steps = vec![Step::default(); 2];
    steps.push(Step {
        joins_early: 30,
        ..Step::default()
    });
    steps.push(Step::default());
    steps.push(Step {
        joins_early: 20,
        ..Step::default()
    });
    steps.push(Step::default());
    let growth = run(zero_fee(), 20_000, 20, &steps);
    out.push_str("\n## 2. Growth burst\n\nSame 200.00 upkeep. 30 people join while period 4 is still being paid (period numbering includes the bootstrap), then 20 more during period 6. Those who paid before the crowd arrived get the difference back as credit at settlement, so everyone's net cost in a period is the same to the cent, and the price keeps falling as the pool grows.\n\n");
    out.push_str(&table(&growth.rows));

    // 3. Churn shock
    let shock_steps = |n: usize| -> Vec<Step> {
        let mut v = vec![Step::default(); n];
        v.push(Step {
            fails: 15,
            ..Step::default()
        });
        v.push(Step::default());
        v.push(Step::default());
        v
    };
    let off = run(zero_fee(), 40_000, 40, &shock_steps(5));
    let on_cfg = Config {
        fee: FeeModel::ZERO,
        reserve_cap_bps: 5_000,
        reserve_surcharge_bps: 500,
        ..Config::default()
    };
    let on = run(on_cfg, 40_000, 40, &shock_steps(5));
    out.push_str("\n## 3. Churn shock, reserve off vs on\n\n40 subscribers, 400.00 upkeep (10.00 each). In period 7, 15 of the 40 fail to pay and lapse. The 25 who pay were quoted 10.00 before anyone knew, so the period lands 150.00 short.\n\n");
    out.push_str("**Reserve off** (the default: no surcharge, so the books break even exactly and no cushion exists). The shortfall becomes a carried deficit and the remaining 25 pay more next period:\n\n");
    out.push_str(&table(&off.rows));
    out.push_str("\n**Reserve on** (5% surcharge until the reserve reaches half a period of upkeep). Everyone pays a little more every period (see the first rows), the reserve absorbs most of the shock, and the next period's price rises less:\n\n");
    out.push_str(&table(&on.rows));
    out.push_str("\nThe trade is visible: the reserve costs a steady premium to smooth a rare spike. That is the owner's call (design doc, section 8).\n");

    // 4. Joiner before vs after coverage
    out.push_str("\n## 4. A joiner before vs after the period is covered\n\nThe example from the product idea: 10 subscribers, 10.00 upkeep, so 1.00 each.\n");
    for (title, early) in [
        ("Joiner arrives after 4 of the 10 have paid", Some(4)),
        ("Joiner arrives after all 10 have paid", None),
    ] {
        let w = joiner_walkthrough(early);
        let _ = write!(
            out,
            "\n### {title}\n\n| who | funds period | charged |\n|---|---:|---:|\n"
        );
        for p in &w.payments {
            let _ = writeln!(
                out,
                "| {} | {} | {} |",
                p.who,
                p.funds_period,
                money(p.charged)
            );
        }
        let min = w.settled_shares.iter().min().copied().unwrap_or(0);
        let max = w.settled_shares.iter().max().copied().unwrap_or(0);
        if early.is_some() {
            let _ = write!(
                out,
                "\nThe joiner pays the lower price (they count themselves) and the price drops for the six renewers still to pay. When the period settles every one of the {} participants has a net share of {} to {} (the 10.00 splits 11 ways with a remainder), and the early payers get {} back in total as credit:\n\n",
                w.settled_shares.len(), money(min), money(max),
                money(w.credits.iter().map(|c| c.1).sum())
            );
            for (who, c) in &w.credits {
                let _ = writeln!(out, "- {who}: {} credit", money(*c));
            }
        } else {
            let _ = write!(
                out,
                "\nThe period was already covered, so the joiner's payment funds period {} instead. The ten renewers each paid exactly {}; nobody is charged extra and nobody waits for a discount. The joiner has access immediately and starts sharing next period's cost.\n",
                w.joiner_period, money(min)
            );
        }
    }

    // 5. Fees
    out.push_str("\n## 5. Processor fees are part of the cost\n\nThe charge is grossed up (Stripe-like 2.9% + 0.30) so the pool receives the share exactly; the owner never absorbs fees and stringcan never keeps the difference.\n\n| share the pool needs | charged | fee |\n|---:|---:|---:|\n");
    for share in [100, 500, 1_000, 2_500] {
        let g = FeeModel::STRIPE_US_CARD.gross_for_net(share);
        let _ = writeln!(
            out,
            "| {} | {} | {} |",
            money(share),
            money(g),
            money(g - share)
        );
    }
    print!("{out}");
}
